// 難しさの上げ方。ステージごとに「つまみ」を少しずつ回す（企画書の 14 章に表あり）
function stageParams(n) {
  const k = n - 1;
  return {
    count: Math.max(11, 20 - Math.floor(k * 0.8)), // 火の玉の数：減っていく＝まばらになる
    ratio: Math.min(0.9, 0.55 + k * 0.05),         // 目標＝火の玉の何割
    ring: Math.max(42, 50 - k * 1.2),              // 輪の基本の半径：小さくなる
    colors: n < 3 ? 3 : 4,                         // 色の数：3色→4色（同色でつなぎにくくなる）
    groups: n <= 2 ? 2 : 3,                        // つながった群れの数（どれも1発で開ける＝3発で必ず満開にできる）
    sameColor: Math.max(0.45, 0.75 - k * 0.04),    // 群れの中で同じ色が続く確率：下がる＝色がまじる
    drift: Math.min(12, 4 + k * 1.2),              // ふわふわ揺れる幅
    big: n >= 2 ? 0.12 : 0,                        // 大玉（助けになる）
    star: 0.1,
    double: n >= 4 ? 0.2 : 0,                                  // 二段玉（2回当てないと開かない）
    doubleMax: n < 4 ? 0 : n < 6 ? 1 : n < 8 ? 2 : 3,          // 1ステージの上限（多すぎると不発続きでテンポが悪い）
    mover: n >= 6 ? Math.min(0.45, 0.25 + (n - 6) * 0.05) : 0, // 流れ玉（横に流れていく）
    moverSpeed: 1 + Math.max(0, n - 6) * 0.1,                 // 流れ玉の速さ（後半ほど速い＝腕前の要素）
    clouds: n >= 5 ? Math.min(3, 1 + Math.floor((n - 5) / 2)) : 0, // 雲（手前にかかって玉を隠す）
  };
}

